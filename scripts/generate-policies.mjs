#!/usr/bin/env node
/** Development/release generation only. Installed assets contain Node built-ins and need no build. */
import { build } from "esbuild";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const check = process.argv.includes("--check");
const banner = "// Generated by scripts/generate-policies.mjs from checked TypeScript. Do not edit.";

async function compile(source, globalName) {
  const result = await build({
    absWorkingDir: root, entryPoints: [source], bundle: true, platform: "node", target: "node22",
    tsconfigRaw: { compilerOptions: { alwaysStrict: true } },
    format: globalName ? "cjs" : "esm",
    write: false, legalComments: "none", banner: { js: banner },
  });
  if (!globalName) return result.outputFiles[0].text;
  // Native requires stay inside each generated closure so one-file ESM tools
  // can bundle policies with Node imports without a runtime package dependency.
  return `import { createRequire as ${globalName}Require } from "node:module";\nconst ${globalName} = (() => {\nconst require = ${globalName}Require(import.meta.url);\nconst module = { exports: {} };\n${result.outputFiles[0].text}\nreturn module.exports;\n})();\n`;
}

const targets = [
  ["src/scrum/cli.ts", "plugin/bin/scrum-doc.mjs"],
  ["src/scrum/config.ts", "plugin/bin/scrum-config.mjs"],
  ["src/vault.ts", "plugin/bin/vault.mjs"],
  ["src/task-status.ts", "plugin/bin/task-status.mjs"],
  ["src/history-upgrade.ts", "plugin/bin/history-upgrade.mjs"],
  ["src/history-import.ts", "plugin/bin/history-import.mjs"],
  ["src/history-stage.ts", "plugin/bin/history-stage.mjs"],
  ["src/scope-policy.ts", "plugin/bin/scope.mjs"],
  ["src/ledger-read.ts", "plugin/bin/ledger-read.mjs"],
  ["src/worktree-policy.ts", "plugin/bin/worktree-policy.mjs"],
  ["src/mcp-launch-policy.ts", "plugin/bin/mcp-launch-policy.mjs"],
  ["src/process-policy.ts", "plugin/bin/process-policy.mjs"],
];
const sections = [
  ["src/task-status.ts", "plugin/bin/bridge.mjs", "GENERATED TASK STATUS POLICY", "taskStatusPolicy"],
  ["src/ledger-validation.ts", "plugin/bin/bridge.mjs", "GENERATED LEDGER POLICY", "ledgerValidationPolicy"],
  ["src/scope-policy.ts", "plugin/bin/agy-pre-tool-hook.mjs", "GENERATED SCOPE POLICY", "scopePolicy"],
  ["src/worktree-policy.ts", "plugin/bin/bridge.mjs", "GENERATED WORKTREE POLICY", "worktreePolicy"],
];
const updates = new Map(await Promise.all(targets.map(async ([source, target]) => [target, await compile(source)])));
for (const [source, target, section, globalName] of sections) {
  let body = updates.get(target) ?? readFileSync(join(root, target), "utf8");
  // The original Ledger section also named its source in the opening marker.
  const begin = body.indexOf(`// BEGIN ${section}`);
  const endMarker = `// END ${section}`;
  const end = body.indexOf(endMarker, begin);
  if (begin < 0 || end < 0) throw new Error(`missing ${section} markers in ${target}`);
  body = body.slice(0, begin) + `// BEGIN ${section}\n${await compile(source, globalName)}${endMarker}` + body.slice(end + endMarker.length);
  updates.set(target, body);
}

const changed = [];
for (const [target, body] of updates) {
  const path = join(root, target);
  if (existsSync(path) && readFileSync(path, "utf8") === body) continue;
  changed.push(target);
  if (!check) writeFileSync(path, body);
}
if (changed.length > 0) {
  console.error(`${check ? "stale generated policy assets" : "generated policy assets"}: ${changed.join(", ")}`);
  if (check) process.exitCode = 1;
} else console.log("generated policy assets in sync");
